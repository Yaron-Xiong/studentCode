    public int minCost(int[][] grid) {
        Map<Integer, Integer>[][] memo = new Map[grid.length][grid[0].length];
        for (Map<Integer, Integer>[] maps : memo) {
            Arrays.setAll(maps, a -> new HashMap<>());
        }
        return dfs2(0, 0, 0, grid, memo);
    }

    private int dfs2(int x, int y, int cost, int[][] grid, Map<Integer, Integer>[][] memo) {
        if (x < 0 || x >= grid.length || y < 0 || y >= grid[0].length) {
            return Integer.MAX_VALUE;
        }
        cost = cost ^ grid[x][y];
        if (memo[x][y].containsKey(cost)) {
            return memo[x][y].get(cost);
        }
        if (x == grid.length - 1 && y == grid[0].length - 1) {
            return cost;
        }
        int a = dfs2(x + 1, y, cost, grid, memo);
        int b = dfs2(x, y + 1, cost, grid, memo);
        memo[x][y].put(cost, Math.min(a, b));
        return Math.min(a, b);
    }
